package io.github.leanish.gradleconventions

import org.assertj.core.api.Assertions.assertThat
import org.gradle.testkit.runner.GradleRunner
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Path

/**
 * The `convention*` configurations of this build mirror what the plugin declares in consumer builds, so the
 * supply-chain gate scans the versions consumers get. This compares both by coordinates (group, artifact and version)
 * per consumer configuration: a mirror missing a module, holding it in the wrong configuration or at another version
 * fails, even when another module shares that version or pulls the missing one transitively.
 */
class ConventionMirrorsTest {
    @TempDir
    lateinit var tempDir: Path

    @Test
    fun mirrorsMatchWhatThePluginDeclaresInAConsumerBuild() {
        val mirrors = mirrors()
        val declared = declaredInConsumer(mirrors.values.flatMap { it.first }.distinct())

        mirrors.forEach { (mirror, consumerConfigurationsAndCoordinates) ->
            val (consumerConfigurations, coordinates) = consumerConfigurationsAndCoordinates
            val expected = consumerConfigurations.flatMap { declared[it].orEmpty() }.toSortedSet()
            assertThat(coordinates.toSortedSet())
                .describedAs("%s mirrors %s", mirror, consumerConfigurations)
                .containsExactlyElementsOf(expected)
        }
    }

    private fun mirrors(): Map<String, Pair<List<String>, List<String>>> {
        val text = checkNotNull(javaClass.classLoader.getResource("convention-mirrors.properties")) {
            "convention-mirrors.properties is generated by writeConventionMirrors"
        }.readText()
        return text.lines().filter(String::isNotBlank).associate { line ->
            val (name, value) = line.split("=", limit = 2)
            val (configurations, coordinates) = value.split("|", limit = 2)
            name to (configurations.split(",") to coordinates.split(",").filter(String::isNotBlank))
        }
    }

    private fun declaredInConsumer(configurations: List<String>): Map<String, List<String>> {
        val projectDir = tempDir.resolve("consumer").toFile()
        projectDir.mkdirs()
        writeRequiredConventionsProperties(projectDir)
        writeFile(projectDir, "settings.gradle.kts", "rootProject.name = \"consumer\"")
        writeFile(
            projectDir,
            "build.gradle.kts",
            """
            plugins {
                id("io.github.leanish.java-conventions")
            }

            tasks.register("printDeclared") {
                val declared = provider {
                    listOf(${configurations.joinToString { "\"$it\"" }}).flatMap { name ->
                        val configuration = configurations.getByName(name)
                        // Only what is declared on the configuration itself (annotationProcessor extends errorprone).
                        // gradle-pitest-plugin adds pitest's as default dependencies, which only `incoming` applies.
                        val dependencies = if (name == "pitest") configuration.incoming.dependencies else configuration.dependencies
                        dependencies.map { "DECLARED ${'$'}name ${'$'}{it.group}:${'$'}{it.name}:${'$'}{it.version}" }
                    }
                }
                doLast { declared.get().forEach(::println) }
            }
            """.trimIndent(),
        )
        val output = GradleRunner.create()
            .withProjectDir(projectDir)
            .withArguments("printDeclared", "--no-configuration-cache", "-q")
            .withPluginClasspath()
            .build()
            .output
        return output.lines()
            .filter { it.startsWith("DECLARED ") }
            .map { it.removePrefix("DECLARED ").split(" ", limit = 2) }
            .groupBy({ it[0] }, { it[1] })
    }
}
