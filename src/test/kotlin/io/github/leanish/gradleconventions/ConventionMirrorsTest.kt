package io.github.leanish.gradleconventions

import org.assertj.core.api.Assertions.assertThat
import org.gradle.testkit.runner.GradleRunner
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Path

/**
 * The `convention*` configurations of this build mirror what the plugin declares in consumer builds, so the
 * supply-chain gate scans the versions consumers get. This compares both by coordinates (group, artifact and version),
 * one consumer configuration at a time. The consumer configurations to check come from the consumer build itself (every
 * configuration the plugin declares something in), not from the mirrors, so removing a whole mirror fails too.
 */
class ConventionMirrorsTest {
    @TempDir
    lateinit var tempDir: Path

    @Test
    fun mirrorsMatchWhatThePluginDeclaresInAConsumerBuild() {
        assertThat(mirrorMismatches(mirrors(), declaredInConsumer())).isEmpty()
    }

    @Test
    fun aConsumerConfigurationWithoutAMirrorFails() {
        val declared = mapOf("errorprone" to setOf("a:b:1"), "compileOnly" to setOf("c:d:1"))
        val mirrors = mapOf("conventionCompileOnly" to Mirror(listOf("compileOnly"), setOf("c:d:1")))

        assertThat(mirrorMismatches(mirrors, declared)).containsExactly("errorprone declares [a:b:1] but no mirror covers it")
    }

    @Test
    fun aModuleMissingFromTheMirrorFails() {
        val declared = mapOf("errorprone" to setOf("a:b:1", "a:c:1"))
        val mirrors = mapOf("conventionErrorprone" to Mirror(listOf("errorprone"), setOf("a:b:1")))

        assertThat(mirrorMismatches(mirrors, declared))
            .containsExactly("conventionErrorprone mirrors errorprone: not mirrored [a:c:1], mirrored but not declared []")
    }

    @Test
    fun aModuleInTheWrongMirrorFails() {
        val declared = mapOf("errorprone" to setOf("a:b:1"), "checkstyle" to setOf("c:d:1"))
        val mirrors = mapOf(
            "conventionErrorprone" to Mirror(listOf("errorprone"), setOf("a:b:1", "c:d:1")),
            "conventionCheckstyle" to Mirror(listOf("checkstyle"), emptySet()),
        )

        assertThat(mirrorMismatches(mirrors, declared)).containsExactlyInAnyOrder(
            "conventionErrorprone mirrors errorprone: not mirrored [], mirrored but not declared [c:d:1]",
            "conventionCheckstyle mirrors checkstyle: not mirrored [c:d:1], mirrored but not declared []",
        )
    }

    @Test
    fun anotherVersionFails() {
        val declared = mapOf("errorprone" to setOf("a:b:2"))
        val mirrors = mapOf("conventionErrorprone" to Mirror(listOf("errorprone"), setOf("a:b:1")))

        assertThat(mirrorMismatches(mirrors, declared))
            .containsExactly("conventionErrorprone mirrors errorprone: not mirrored [a:b:2], mirrored but not declared [a:b:1]")
    }

    @Test
    fun eachConsumerConfigurationOfASharedMirrorIsComparedOnItsOwn() {
        val declared = mapOf("compileOnly" to setOf("a:b:1", "c:d:1"), "testCompileOnly" to setOf("a:b:1"))
        val mirrors = mapOf("conventionCompileOnly" to Mirror(listOf("compileOnly", "testCompileOnly"), setOf("a:b:1", "c:d:1")))

        assertThat(mirrorMismatches(mirrors, declared))
            .containsExactly("conventionCompileOnly mirrors testCompileOnly: not mirrored [], mirrored but not declared [c:d:1]")
    }

    @Test
    fun aMirroredConfigurationTheConsumerDoesNotHaveFails() {
        val mirrors = mapOf("conventionPitest" to Mirror(listOf("pitest"), setOf("a:b:1")))

        assertThat(mirrorMismatches(mirrors, emptyMap()))
            .containsExactly("conventionPitest mirrors pitest, which the consumer build doesn't have")
    }

    private fun mirrors(): Map<String, Mirror> {
        val text = checkNotNull(javaClass.classLoader.getResource("convention-mirrors.properties")) {
            "convention-mirrors.properties is generated by writeConventionMirrors"
        }.readText()
        return text.lines().filter(String::isNotBlank).associate { line ->
            val (name, value) = line.split("=", limit = 2)
            val (configurations, coordinates) = value.split("|", limit = 2)
            name to Mirror(configurations.split(","), coordinates.split(",").filter(String::isNotBlank).toSet())
        }
    }

    /** Every configuration of a consumer build that applies only the plugin, with the coordinates declared on it. */
    private fun declaredInConsumer(): Map<String, Set<String>> {
        val projectDir = tempDir.resolve("consumer").toFile()
        projectDir.mkdirs()
        writeRequiredConventionsProperties(projectDir)
        writeFile(projectDir, "settings.gradle.kts", "rootProject.name = \"consumer\"")
        writeFile(
            projectDir,
            "build.gradle.kts",
            """
            plugins {
                id("io.github.leanish.java-conventions")
            }

            tasks.register("printDeclared") {
                val declared = provider {
                    configurations.flatMap { configuration ->
                        val name = configuration.name
                        // Only what is declared on the configuration itself (annotationProcessor extends errorprone).
                        // gradle-pitest-plugin adds pitest's as default dependencies, which only `incoming` applies.
                        val dependencies = if (name == "pitest") configuration.incoming.dependencies else configuration.dependencies
                        listOf("CONFIGURATION ${'$'}name") +
                            dependencies.map { "DECLARED ${'$'}name ${'$'}{it.group}:${'$'}{it.name}:${'$'}{it.version}" }
                    }
                }
                doLast { declared.get().forEach(::println) }
            }
            """.trimIndent(),
        )
        val output = GradleRunner.create()
            .withProjectDir(projectDir)
            .withArguments("printDeclared", "--no-configuration-cache", "-q")
            .withPluginClasspath()
            .build()
            .output
        val lines = output.lines()
        val configurations = lines.filter { it.startsWith("CONFIGURATION ") }.map { it.removePrefix("CONFIGURATION ") }
        check(configurations.isNotEmpty()) { "the consumer build printed no configurations:\n$output" }
        val declared = lines.filter { it.startsWith("DECLARED ") }
            .map { it.removePrefix("DECLARED ").split(" ", limit = 2) }
            .groupBy({ it[0] }, { it[1] })
        return configurations.associateWith { declared[it].orEmpty().toSet() }
    }
}

/** A `convention*` mirror: the consumer configurations it stands for, and the coordinates it declares. */
internal data class Mirror(val consumerConfigurations: List<String>, val coordinates: Set<String>)

/**
 * What doesn't match between [mirrors] and a consumer build's [declared] coordinates (every configuration the consumer
 * has, mapped to what is declared on it): every configuration with declarations needs a mirror, every mirrored
 * configuration must exist, and each must declare exactly its mirror's coordinates. Empty when everything matches.
 */
internal fun mirrorMismatches(mirrors: Map<String, Mirror>, declared: Map<String, Set<String>>): List<String> {
    val mirrorOf = mutableMapOf<String, String>()
    val mismatches = mutableListOf<String>()
    mirrors.forEach { (name, mirror) ->
        mirror.consumerConfigurations.forEach { configuration ->
            mirrorOf.put(configuration, name)?.let { other -> mismatches += "$configuration is mirrored by both $other and $name" }
        }
    }
    declared.filter { (configuration, coordinates) -> coordinates.isNotEmpty() && configuration !in mirrorOf }
        .toSortedMap()
        .forEach { (configuration, coordinates) -> mismatches += "$configuration declares ${coordinates.sorted()} but no mirror covers it" }
    mirrors.forEach { (name, mirror) ->
        mirror.consumerConfigurations.forEach { configuration ->
            val actual = declared[configuration]
            if (actual == null) {
                mismatches += "$name mirrors $configuration, which the consumer build doesn't have"
            } else if (actual != mirror.coordinates) {
                mismatches += "$name mirrors $configuration: not mirrored ${(actual - mirror.coordinates).sorted()}, " +
                    "mirrored but not declared ${(mirror.coordinates - actual).sorted()}"
            }
        }
    }
    return mismatches
}
